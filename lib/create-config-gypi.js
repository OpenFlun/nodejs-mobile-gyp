import gracefulFs from 'graceful-fs'
import * as log from './log.js'
import path from 'path'

const fs = gracefulFs.promises

/**
 * 解析 config.gypi 内容为 JSON 对象
 * 逻辑翻译自 Node.js 的 tools/js2c.py
 */
const parseConfigGypi = (config) => {
  // 1. 去掉 # 注释
  config = config.replace(/#.*/g, '')
  // 2. 拼接多行字符串
  config = config.replace(/'$\s+'/mg, '')
  // 3. 把单引号字符串归一化为双引号
  config = config.replace(/'/g, '"')
  return JSON.parse(config)
}

/**
 * 读取基础 config.gypi
 */
const getBaseConfigGypi = async ({ gyp, nodeDir }) => {
  // 在以下情况优先读取 $nodeDir/include/node/config.gypi：
  // 1. 指定了 --dist-url 或 --nodedir
  // 2. 且没有指定 --force-process-config
  const useCustomHeaders = gyp.opts.nodedir || gyp.opts.disturl || gyp.opts['dist-url']
  const shouldReadConfigGypi = useCustomHeaders && !gyp.opts['force-process-config']
  if (shouldReadConfigGypi && nodeDir) {
    try {
      const baseConfigGypiPath = path.resolve(nodeDir, 'include/node/config.gypi')
      const baseConfigGypi = await fs.readFile(baseConfigGypiPath)
      return parseConfigGypi(baseConfigGypi.toString())
    } catch (err) {
      log.warn('read config.gypi', err.message)
    }
  }

  // 回退到 process.config
  return JSON.parse(JSON.stringify(process.config))
}

/**
 * 基于当前环境生成 config.gypi 内容
 */
const getCurrentConfigGypi = async ({ gyp, nodeDir, vsInfo, python }) => {
  const config = await getBaseConfigGypi({ gyp, nodeDir })
  if (!config.target_defaults) {
    config.target_defaults = {}
  }
  if (!config.variables) {
    config.variables = {}
  }

  const defaults = config.target_defaults
  const variables = config.variables

  // 不要继承 base config.gypi 的 defaults，
  // 否则当 node 可执行文件在另一台机器编译（lib/include 路径不同）时会出问题
  defaults.cflags = []
  defaults.defines = []
  defaults.include_dirs = []
  defaults.libraries = []

  // 设置 default_configuration
  if ('debug' in gyp.opts) {
    defaults.default_configuration = gyp.opts.debug ? 'Debug' : 'Release'
  }

  if (!defaults.default_configuration) {
    defaults.default_configuration = 'Release'
  }

  // 设置 target_arch
  variables.target_arch = gyp.opts.arch || process.arch || 'ia32'
  if (variables.target_arch === 'arm64') {
    defaults.msvs_configuration_platform = 'ARM64'
    defaults.xcode_configuration_platform = 'arm64'
  }

  // 设置 Node 开发目录
  variables.nodedir = nodeDir

  // 设置 Python 路径
  variables.python = python

  // 默认禁用 -T "thin" 静态归档
  variables.standalone_static_library = gyp.opts.thin ? 0 : 1

  if (process.platform === 'win32') {
    defaults.msbuild_toolset = vsInfo.toolset
    if (vsInfo.sdk) {
      defaults.msvs_windows_target_platform_version = vsInfo.sdk
    }
    if (variables.target_arch === 'arm64') {
      if (vsInfo.versionMajor > 15 ||
          (vsInfo.versionMajor === 15 && vsInfo.versionMajor >= 9)) {
        defaults.msvs_enable_marmasm = 1
      } else {
        log.warn('Compiling ARM64 assembly is only available in\n' +
          'Visual Studio 2017 version 15.9 and above')
      }
    }
    variables.msbuild_path = vsInfo.msBuild
    // Windows 原生构建走 MSVC 工具集：必须关闭 clang 与 LTO，
    // 否则 common.gypi 会把 toolset 设为 ClangCL，并向 MSVC 链接器传入 Clang 专用参数
    // （-flto=thin、/opt:lldltojobs），导致 MSB8020 或 LNK1117
    if (!gyp.opts.format || gyp.opts.format === 'msvs') {
      variables.clang = 0
      variables.enable_lto = 'false'
      variables.enable_thin_lto = 'false'
      variables.lto_jobs = ''
    }
  }

  // 把其余未知选项当作变量写入，支持模块自定义 configure 参数，例如：
  //   $ node-gyp configure --shared-libxml2
  Object.keys(gyp.opts).forEach(function (opt) {
    if (opt === 'argv') {
      return
    }
    if (opt in gyp.configDefs) {
      return
    }
    variables[opt.replace(/-/g, '_')] = gyp.opts[opt]
  })

  return config
}

/**
 * 生成并写出 config.gypi 文件
 */
const createConfigGypi = async ({ gyp, buildDir, nodeDir, vsInfo, python }) => {
  const configFilename = 'config.gypi'
  const configPath = path.resolve(buildDir, configFilename)

  log.verbose('build/' + configFilename, 'creating config file')

  const config = await getCurrentConfigGypi({ gyp, nodeDir, vsInfo, python })

  // 保证 config.gypi 中的布尔值都转成字符串
  const boolsToString = (k, v) => {
    if (typeof v === 'boolean') {
      return String(v)
    }
    return v
  }

  log.silly('build/' + configFilename, config)

  // 把 config.gypi 写入 build/ 目录
  const prefix = '# Do not edit. File was generated by node-gyp\'s "configure" step'

  const json = JSON.stringify(config, boolsToString, 2)
  log.verbose('build/' + configFilename, 'writing out config file: %s', configPath)
  await fs.writeFile(configPath, [prefix, json, ''].join('\n'))

  return configPath
}

export { createConfigGypi, parseConfigGypi, getCurrentConfigGypi }
